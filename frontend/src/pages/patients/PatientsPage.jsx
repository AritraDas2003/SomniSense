import { useCallback, useEffect, useState } from 'react'
import { Plus } from 'lucide-react'
import { Link } from 'react-router-dom'
import PageHeader from '../../components/common/PageHeader'
import PatientsTable from '../../components/common/PatientsTable'
import { getPatients } from '../../services/patientService'

export default function PatientsPage() {
  const [patients, setPatients] = useState([])
  const [loading, setLoading] = useState(true)
  const [error, setError] = useState('')

  const loadPatients = useCallback(async () => {
    setLoading(true)
    setError('')
    try {
      setPatients(await getPatients())
    } catch (loadError) {
      setError(loadError.message || 'The patient list could not be loaded.')
    } finally {
      setLoading(false)
    }
  }, [])

  useEffect(() => {
    let active = true
    getPatients()
      .then((patientRows) => { if (active) setPatients(patientRows) })
      .catch((loadError) => { if (active) setError(loadError.message || 'The patient list could not be loaded.') })
      .finally(() => { if (active) setLoading(false) })
    return () => { active = false }
  }, [])

  return (
    <div className="page-stack">
      <PageHeader
        eyebrow="CARE WORKSPACE"
        title="Patients"
        description="Review patient records, device links, and the freshness of available readings."
        actions={<Link className="button button-primary" to="/patients/new"><Plus size={17} /> Add patient</Link>}
      />
      {error && <div className="error-state" role="alert"><div><strong>Patient list unavailable</strong><p>{error}</p></div><button className="button button-outline" onClick={loadPatients}>Try again</button></div>}
      {loading ? (
        <div className="panel loading-panel"><span className="spinner" /><span>Loading patient records...</span></div>
      ) : (
        <PatientsTable patients={patients} />
      )}
      <p className="subtle-note">Patient codes are generated by the service. Missing measurements are shown as — and are never treated as zero.</p>
    </div>
  )
}
