import { useCallback, useEffect, useState } from 'react'
import { Plus } from 'lucide-react'
import { Link } from 'react-router-dom'
import PageHeader from '../../components/common/PageHeader'
import PatientsTable from '../../components/common/PatientsTable'
import { useMockApi } from '../../services/api/apiConfig'
import { getPatients } from '../../services/patientService'

const PAGE_SIZE = 10

export default function PatientsPage() {
  const mockMode = useMockApi
  const [pageData, setPageData] = useState({
    content: [],
    page: 0,
    size: PAGE_SIZE,
    totalElements: 0,
    totalPages: 0,
  })
  const [page, setPage] = useState(0)
  const [filters, setFilters] = useState({ q: '', sourceType: 'ALL', status: 'ALL' })
  const [loading, setLoading] = useState(true)
  const [error, setError] = useState('')

  const loadPatients = useCallback(async () => {
    setLoading(true)
    setError('')
    try {
      const response = await getPatients({
        page,
        size: PAGE_SIZE,
        q: filters.q,
        sourceType: filters.sourceType,
        status: filters.status,
      })
      setPageData(response)
    } catch (loadError) {
      setError(loadError.message || 'The patient list could not be loaded.')
    } finally {
      setLoading(false)
    }
  }, [page, filters])

  useEffect(() => {
    let active = true
    const timer = window.setTimeout(() => {
      setLoading(true)
      setError('')
      getPatients({
        page,
        size: PAGE_SIZE,
        q: filters.q,
        sourceType: filters.sourceType,
        status: filters.status,
      })
        .then((response) => {
          if (active) setPageData(response)
        })
        .catch((loadError) => {
          if (active) setError(loadError.message || 'The patient list could not be loaded.')
        })
        .finally(() => {
          if (active) setLoading(false)
        })
    }, filters.q ? 200 : 0)

    return () => {
      active = false
      window.clearTimeout(timer)
    }
  }, [page, filters])

  function handleFiltersChange(nextFilters) {
    setFilters(nextFilters)
    setPage(0)
  }

  return (
    <div className="page-stack">
      <PageHeader
        eyebrow="CARE WORKSPACE"
        title="Patients"
        description="Review patient records, assigned devices, active monitoring sessions, and latest readings."
        actions={<Link className="button button-primary" to="/patients/new"><Plus size={17} /> Add patient</Link>}
      />
      {error && (
        <div className="error-state" role="alert">
          <div><strong>Patient list unavailable</strong><p>{error}</p></div>
          <button className="button button-outline" onClick={loadPatients}>Try again</button>
        </div>
      )}
      {loading && pageData.content.length === 0 ? (
        <div className="panel loading-panel"><span className="spinner" /><span>Loading patient records...</span></div>
      ) : (
        <PatientsTable
          patients={pageData.content}
          pageInfo={pageData}
          onPageChange={setPage}
          filters={filters}
          onFiltersChange={handleFiltersChange}
          workspaceLabel={mockMode ? 'in this demo workspace' : 'from SomniSense API'}
        />
      )}
      <p className="subtle-note">Patient codes are generated by the service. Missing measurements are shown as — and are never treated as zero.</p>
    </div>
  )
}
