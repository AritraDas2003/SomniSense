package com.somnisense.backend.patient.entity;

import com.somnisense.backend.common.domain.SourceType;
import com.somnisense.backend.common.persistence.AssignedIdEntity;
import jakarta.persistence.Column;
import jakarta.persistence.Entity;
import jakarta.persistence.EnumType;
import jakarta.persistence.Enumerated;
import jakarta.persistence.Table;
import org.hibernate.annotations.DynamicUpdate;

import java.time.Instant;
import java.time.LocalDate;
import java.util.Objects;
import java.util.UUID;

import static com.somnisense.backend.common.util.Strings.clean;

/**
 * A monitored patient. Maps 1:1 to the approved "patients" table.
 *
 * - patientCode is generated by the backend (PatientCodeGenerator) and never changes.
 * - sourceType (PHYSICAL / SIMULATED) is fixed at registration: devices, sessions and readings rely on it
 *   to keep simulated data separate from physical data.
 * - createdBy is the id of the staff member who registered the patient, taken from the session.
 * - date_of_birth is a plain calendar date (PostgreSQL "date") -> LocalDate, no time zone.
 *
 * Contact and medical details live in their own tables (PatientContact, PatientMedicalDetails), linked by
 * patient_id. There are deliberately no JPA relationships/cascades here.
 */
@Entity
@Table(name = "patients")
@DynamicUpdate
public class Patient extends AssignedIdEntity {

    @Column(name = "patient_code", nullable = false, unique = true, length = 30, updatable = false)
    private String patientCode;

    @Column(name = "full_name", nullable = false, length = 150)
    private String fullName;

    @Column(name = "alias", length = 100)
    private String alias;

    @Column(name = "date_of_birth")
    private LocalDate dateOfBirth;

    @Enumerated(EnumType.STRING)
    @Column(name = "gender", length = 30)
    private Gender gender;

    @Enumerated(EnumType.STRING)
    @Column(name = "source_type", nullable = false, length = 20, updatable = false)
    private SourceType sourceType;

    @Enumerated(EnumType.STRING)
    @Column(name = "status", nullable = false, length = 20)
    private PatientStatus status;

    @Column(name = "created_by", nullable = false, updatable = false)
    private UUID createdBy;

    @Column(name = "created_at", nullable = false, updatable = false)
    private Instant createdAt;

    @Column(name = "updated_at", nullable = false)
    private Instant updatedAt;

    protected Patient() {
    }

    public Patient(String patientCode, String fullName, String alias, LocalDate dateOfBirth, Gender gender,
                   SourceType sourceType, UUID createdBy) {
        super(UUID.randomUUID());
        this.patientCode = Objects.requireNonNull(patientCode, "patientCode");
        this.fullName = Objects.requireNonNull(clean(fullName), "fullName");
        this.alias = clean(alias);
        this.dateOfBirth = dateOfBirth;
        this.gender = gender;
        this.sourceType = Objects.requireNonNull(sourceType, "sourceType");
        this.status = PatientStatus.ACTIVE;
        this.createdBy = Objects.requireNonNull(createdBy, "createdBy");
        Instant now = Instant.now();
        this.createdAt = now;
        this.updatedAt = now;
    }

    /** Replaces the editable profile fields. Returns true if anything actually changed. */
    public boolean updateProfile(String fullName, String alias, LocalDate dateOfBirth, Gender gender) {
        String newName = Objects.requireNonNull(clean(fullName), "fullName");
        String newAlias = clean(alias);
        boolean changed = !newName.equals(this.fullName) || !Objects.equals(newAlias, this.alias)
                || !Objects.equals(dateOfBirth, this.dateOfBirth) || gender != this.gender;
        if (changed) {
            this.fullName = newName;
            this.alias = newAlias;
            this.dateOfBirth = dateOfBirth;
            this.gender = gender;
            touch();
        }
        return changed;
    }

    public void changeStatus(PatientStatus newStatus) {
        this.status = Objects.requireNonNull(newStatus, "status");
        touch();
    }

    /** Called when contact/medical details change, so "last updated" on the patient reflects them too. */
    public void touch() {
        this.updatedAt = Instant.now();
    }

    public String getPatientCode() {
        return patientCode;
    }

    public String getFullName() {
        return fullName;
    }

    public String getAlias() {
        return alias;
    }

    public LocalDate getDateOfBirth() {
        return dateOfBirth;
    }

    public Gender getGender() {
        return gender;
    }

    public SourceType getSourceType() {
        return sourceType;
    }

    public PatientStatus getStatus() {
        return status;
    }

    public UUID getCreatedBy() {
        return createdBy;
    }

    public Instant getCreatedAt() {
        return createdAt;
    }

    public Instant getUpdatedAt() {
        return updatedAt;
    }
}
